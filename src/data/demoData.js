function buildShenzhenForecast(currentDepth, forecast15, forecast30, forecast60) {
  return [
    { minute: 0, depth: currentDepth },
    { minute: 5, depth: Math.round(currentDepth + (forecast15 - currentDepth) / 3) },
    { minute: 10, depth: Math.round(currentDepth + ((forecast15 - currentDepth) * 2) / 3) },
    { minute: 15, depth: forecast15 },
    { minute: 30, depth: forecast30 },
    { minute: 45, depth: Math.round((forecast30 + forecast60) / 2) },
    { minute: 60, depth: forecast60 },
  ];
}

function createShenzhenSite(site) {
  return {
    online: true,
    ...site,
    forecast: buildShenzhenForecast(
      site.currentDepth,
      site.forecast15,
      site.forecast30,
      site.forecast60,
    ),
  };
}

